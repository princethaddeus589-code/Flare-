// Bubble-shaped button with a "tail" corner and a tap ripple, in the spirit of a chat app.
export function Btn({ kind = "primary", icon, children, className = "", onClick, ...rest }) {
  const ref = useRef();
  const press = (e) => {
    const el = ref.current, r = el.getBoundingClientRect();
    const s = document.createElement("span");
    s.className = "ripple";
    s.style.left = e.clientX - r.left + "px";
    s.style.top = e.clientY - r.top + "px";
    el.appendChild(s);
    setTimeout(() => s.remove(), 600);
  };
  return (
    <button ref={ref} className={`btn ${kind} ${className}`} onPointerDown={press} onClick={onClick} {...rest}>
      {icon && <span className="chip">{icon}</span>}
      <span>{children}</span>
    </button>
  );
}
